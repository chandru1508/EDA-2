import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

df = pd.read_csv('/content/superstore_raw.csv')

df.head()

category_sales = df.groupby(df['Category'].str.title())['Sales'].sum().reset_index()

plt.figure(figsize=(5,5))
sns.barplot(data=category_sales, x='Category', y='Sales')

plt.title('Total Sales')
plt.xlabel('Category')
plt.ylabel('Sales')


plt.show()

plt.figure(figsize=(5,5))
sns.boxplot(data=df, x='Profit')

plt.title('Profit Distribution')
plt.xlabel('Profit')
plt.show()

plt.figure(figsize=(5,5))
sns.scatterplot(data=df, x='Discount', y='Profit')

plt.title('Discount vs Profit')
plt.xlabel('Discount')
plt.ylabel('Profit')

plt.show()

numeric_df = df.select_dtypes(include=['float64', 'int64'])
corr_matrix = numeric_df.corr()

plt.figure(figsize=(5,5))
sns.heatmap(corr_matrix,annot=True, cmap='coolwarm',  linewidths=0.5)

plt.title('Correlation Matrix')
plt.show()

category_profit = df.groupby(df['Category'].str.title())['Profit'].sum().reset_index()

plt.figure(figsize=(5,5))
sns.barplot(data=category_profit, x='Category', y='Profit')

plt.title('Total Sales')
plt.xlabel('Category')
plt.ylabel('Profit')


plt.show()